        if len(entrada) != 1 or not entrada.isalpha():
            print("Por favor, introduce una sola letra válida o escribe 'pista'.")
            continue

        if entrada in letras_adivinadas or entrada in letras_incorrectas:
            print("Ya has intentado con esa letra. ¡Prueba otra!")
            continue

